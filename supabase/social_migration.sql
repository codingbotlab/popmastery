-- Keep a public profile in sync for users who already exist and future users.
insert into public.public_profiles (id, username, display_name, avatar_url)
select p.id,
       lower(regexp_replace(coalesce(nullif(p.display_name, ''), 'learner'), '[^a-zA-Z0-9_]+', '-', 'g')) || '-' || substr(p.id::text, 1, 6),
       coalesce(nullif(p.display_name, ''), 'Learner'),
       p.avatar_url
from public.profiles p
on conflict (id) do nothing;

create or replace function public.handle_new_social_profile()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  base_username text;
begin
  base_username := lower(regexp_replace(coalesce(nullif(new.raw_user_meta_data->>'display_name', ''), split_part(coalesce(new.email, ''), '@', 1), 'learner'), '[^a-zA-Z0-9_]+', '-', 'g'));
  if base_username = '' then base_username := 'learner'; end if;
  insert into public.public_profiles (id, username, display_name, avatar_url)
  values (new.id, base_username || '-' || substr(new.id::text, 1, 6), coalesce(new.raw_user_meta_data->>'display_name', split_part(coalesce(new.email, ''), '@', 1), 'Learner'), new.raw_user_meta_data->>'avatar_url')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_social_profile_created on auth.users;
create trigger on_auth_social_profile_created
after insert on auth.users
for each row execute procedure public.handle_new_social_profile();
