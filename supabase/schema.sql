create policy "profiles_insert_own" on public.profiles for insert with check (auth.uid() = id);
create policy "profiles_update_own" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "results_select_own" on public.game_results for select using (auth.uid() = user_id);
create policy "results_insert_own" on public.game_results for insert with check (auth.uid() = user_id);

create policy "events_select_own" on public.activity_events for select using (auth.uid() = user_id);
create policy "events_insert_own" on public.activity_events for insert with check (auth.uid() = user_id);

create policy "interests_select_own" on public.user_interests for select using (auth.uid() = user_id);
create policy "interests_insert_own" on public.user_interests for insert with check (auth.uid() = user_id);
create policy "interests_update_own" on public.user_interests for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, email, avatar_url, provider, metadata, last_login_at)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'full_name', split_part(coalesce(new.email, ''), '@', 1), 'Learner'),
    new.email,
    coalesce(new.raw_user_meta_data->>'avatar_url', new.raw_user_meta_data->>'picture'),
    coalesce(new.raw_app_meta_data->>'provider', 'email'),
    coalesce(new.raw_user_meta_data, '{}'::jsonb),
    now()
  )
  on conflict (id) do update set
    email = excluded.email,
    avatar_url = coalesce(excluded.avatar_url, public.profiles.avatar_url),
    provider = excluded.provider,
    metadata = excluded.metadata,
    updated_at = now(),
    last_login_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create index if not exists game_results_user_played_idx on public.game_results(user_id, played_at desc);
