drop policy if exists "profiles_update_own" on public.profiles;
drop policy if exists "results_select_own" on public.game_results;
drop policy if exists "results_insert_own" on public.game_results;
drop policy if exists "events_select_own" on public.activity_events;
drop policy if exists "events_insert_own" on public.activity_events;
